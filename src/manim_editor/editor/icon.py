"""Locate and load the application icon.

The committed asset ``manim_editor/assets/manim_editor.ico`` is generated by
``packaging/make_icon.py`` and ships inside the package so a source checkout and
a frozen/installed build both find it. Source checkouts that predate the asset
fall back to the build copy under ``packaging/``.
"""

from __future__ import annotations

from pathlib import Path

from PySide6.QtGui import QIcon

__all__ = ["ICON_FILENAME", "icon_path", "load_icon"]

ICON_FILENAME = "manim_editor.ico"


def icon_path() -> Path | None:
    """Return the icon file, or ``None`` when no asset is available."""
    package_root = Path(__file__).resolve().parents[1]
    candidates = (
        package_root / "assets" / ICON_FILENAME,
        # Running from a checkout whose assets were not generated yet.
        package_root.parents[1] / "packaging" / ICON_FILENAME,
    )
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


def load_icon() -> QIcon:
    """Return the application :class:`QIcon`.

    An empty ``QIcon`` is returned when the asset is missing, which leaves Qt's
    default icon in place instead of crashing the editor.
    """
    path = icon_path()
    return QIcon(str(path)) if path is not None else QIcon()
