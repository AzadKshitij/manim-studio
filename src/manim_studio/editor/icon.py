"""Locate and load the application icon.

The icon is any ``*.ico`` in the packaged ``manim_studio/assets`` directory, so a
replacement can simply be dropped in. The committed default,
``manim_studio.ico``, is generated by ``packaging/make_icon.py`` and ships inside
the package so a source checkout and a frozen/installed build both find it.
Source checkouts that predate the asset fall back to the build copy under
``packaging/``.
"""

from __future__ import annotations

from pathlib import Path

from PySide6.QtGui import QIcon

__all__ = ["ICON_FILENAME", "icon_path", "load_icon"]

ICON_FILENAME = "manim_studio.ico"


def _pick_icon(assets_dir: Path) -> Path | None:
    """Return the icon to use from *assets_dir*, or ``None`` when empty.

    Any dropped-in ``*.ico`` overrides the generated :data:`ICON_FILENAME`;
    ties (and the common single-file case) resolve alphabetically so the choice
    is deterministic.
    """
    icons = [path for path in assets_dir.glob("*.ico") if path.is_file()]
    if not icons:
        return None
    icons.sort(key=lambda path: (path.name == ICON_FILENAME, path.name.lower()))
    return icons[0]


def icon_path() -> Path | None:
    """Return the icon file, or ``None`` when no asset is available."""
    package_root = Path(__file__).resolve().parents[1]
    found = _pick_icon(package_root / "assets")
    if found is not None:
        return found
    # Running from a checkout whose assets were not generated yet.
    build_copy = package_root.parents[1] / "packaging" / ICON_FILENAME
    return build_copy if build_copy.is_file() else None


def load_icon() -> QIcon:
    """Return the application :class:`QIcon`.

    An empty ``QIcon`` is returned when the asset is missing, which leaves Qt's
    default icon in place instead of crashing the editor.
    """
    path = icon_path()
    return QIcon(str(path)) if path is not None else QIcon()
